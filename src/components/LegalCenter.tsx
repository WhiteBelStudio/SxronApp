function DocumentModal({ kind, onClose }: { kind: "rules" | "policy"; onClose: () => void }) {
  const isRules = kind === "rules";
  const sections = isRules ? RULES_SECTIONS : POLICY_SECTIONS;
  return (
    <div className="sxron-legal-backdrop" onClick={onClose}>
      <section className="sxron-legal-modal" onClick={(event) => event.stopPropagation()} role="dialog" aria-modal="true" aria-label={isRules ? "Правила SXRON Marketplace" : "Политика SXRON Marketplace"}>
        <div className="sxron-legal-head">
          <div>
            <span>{isRules ? "SXRON MARKETPLACE" : "SXRON PRIVACY"}</span>
            <h2>{isRules ? "Правила площадки" : "Политика"}</h2>
            <p>{isRules ? "Строгие правила для продавцов и покупателей." : "Общие принципы обработки и защиты информации."}</p>
          </div>
          <button onClick={onClose} aria-label="Закрыть">×</button>
        </div>
        <div className="sxron-legal-list">
          {sections.map((section) => (
            <article key={section.title}>
              <h3>{section.title}</h3>
              <p>{section.body}</p>
            </article>
          ))}
        </div>
        <div className="sxron-legal-footer">
          {isRules ? "Используя SXRON Marketplace, пользователь подтверждает согласие соблюдать актуальную редакцию правил." : "Политика не заменяет обязательные требования применимого законодательства."}
        </div>
      </section>
    </div>
  );
}

export default function LegalCenter() {
  const [document, setDocument] = useState<"rules" | "policy" | null>(null);

  useEffect(() => {
    const onKey = (event: KeyboardEvent) => {
      if (event.key === "Escape") setDocument(null);
    };
    window.addEventListener("keydown", onKey);
    return () => window.removeEventListener("keydown", onKey);
  }, []);

  return (
    <>
      <div className="sxron-legal-buttons">
        <button type="button" onClick={() => setDocument("rules")}>📜 Правила</button>
        <button type="button" onClick={() => setDocument("policy")}>🛡 Политика</button>
      </div>
      {document && <DocumentModal kind={document} onClose={() => setDocument(null)} />}
    </>
  );
}
